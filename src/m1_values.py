"""Write report/m1/values.tex: every number the M1 report prints comes from here,
so the PDF always matches team.json and the generated instance.

Usage:  python src/m1_values.py [team.json] [instances_dir] [output .tex]
"""
import json
import platform
import sys
from pathlib import Path

from team_seed import load_team, team_seed, last_four


def tex_escape(s):
    repl = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
            "^": r"\textasciicircum{}"}
    return "".join(repl.get(ch, ch) for ch in str(s))


if __name__ == "__main__":
    team_file = sys.argv[1] if len(sys.argv) > 1 else "team.json"
    inst_dir = Path(sys.argv[2] if len(sys.argv) > 2 else "instances")
    out = Path(sys.argv[3] if len(sys.argv) > 3 else "report/m1/values.tex")

    team = load_team(team_file)
    mode = team.get("seed_mode", "last4_number")
    seed, terms = team_seed(team["members"], mode)
    stem = (inst_dir / "medidrone_current.txt").read_text().strip()
    inst = json.loads((inst_dir / f"{stem}.json").read_text())
    metric = json.loads((inst_dir / f"{stem}_metric.json").read_text())
    if inst["seed"] != seed:
        sys.exit("instance was generated with another seed - run the generator first")

    eu = sum(c["side"] == "EU" for c in inst["customers"])
    rows = "\n".join(
        f"{tex_escape(m['name'])} & {tex_escape(m['student_id'])} & "
        f"{last_four(m['student_id'])} \\\\" for m in team["members"])
    if mode == "last4_number":
        seed_formula = " + ".join(str(t) for t in terms)
        mode_text = ("the last four digits of each ID are read as one four-digit number "
                     "and these numbers are added")
    else:
        seed_formula = " + ".join(
            "(" + "+".join(last_four(m["student_id"])) + ")" for m in team["members"])
        mode_text = "the last four digits of every ID are added one by one"

    neutral = metric["neutral_depot"]
    macros = {
        "IsPlaceholder": "1" if team.get("placeholder") else "0",
        "TeamSeed": str(seed),
        "SeedFormula": seed_formula,
        "SeedModeText": mode_text,
        "InstanceName": tex_escape(inst["name"]),
        "InstanceFile": tex_escape(f"instances/{stem}.vrp"),
        "NumClusters": str(len(inst["clusters"])),
        "NumEU": str(eu),
        "NumAS": str(inst["n"] - eu),
        "NumRandom": str(sum(c["cluster"] < 0 for c in inst["customers"])),
        "NumClustered": str(sum(c["cluster"] >= 0 for c in inst["customers"])),
        "ClusterSizes": ", ".join(str(c["size"]) for c in inst["clusters"]),
        "TotalDemand": str(inst["total_demand"]),
        "LowerBoundK": str(inst["vehicle_lower_bound"]),
        "FleetK": str(inst["vehicles"]),
        "FFDK": str(inst["ffd_vehicles"]),
        "Triples": f"{metric['triples_checked']:,}".replace(",", "{,}"),
        "RuleViolations": str(metric["rule_as_written"]["violating_triples"]),
        "NeutralViolations": f"{neutral['violating_triples']:,}".replace(",", "{,}"),
        "NeutralMax": f"{neutral['max_violation']:.1f}",
        "PythonVersion": platform.python_version(),
    }
    lines = ["% generated by src/m1_values.py - do not edit by hand"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    lines.append("\\newcommand{\\MemberRows}{" + rows + "}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"written: {out}")
